def validate_completion(marker, freeze, freeze_sha):
    expected = set(CASES)
    if (marker.get('oracle_read') is not False or set(marker.get('cases', [])) != expected
            or len(marker.get('cases', [])) != len(expected)
            or marker.get('all_predictions_terminal_before_reference_access') is not True
            or marker.get('freeze_sha256') != freeze_sha):
        raise ValueError('Both distinct held-control predictions must finish before oracle access')
    complete, failed = marker.get('completed', []), marker.get('failed', [])
    if (len(complete) != len(set(complete)) or len(failed) != len(set(failed))
            or set(complete) & set(failed) or set(complete) | set(failed) != expected):
        raise ValueError('Inconsistent terminal prediction statuses')
    if (freeze.get('oracle_read') is not False or freeze.get('source_input') is not False
            or freeze.get('project_execution') is not False
            or freeze.get('fresh_scanners') is not True
            or freeze.get('fresh_physical_reads') is not True
            or freeze.get('java_archive_components_default') is not True
            or freeze.get('java_archive_components_override_supplied') is not False
            or set(freeze.get('cases', [])) != expected
            or freeze.get('fresh_blind_independent_claim') is not False):
        raise ValueError('Held controls require the actual default/no-oracle/fresh image mode')


def frozen_source_sets(code):
    sources, caches = {}, {}
    for name, expected in code.items():
        path = safe_relative(name)
        if '__pycache__' in path.parts or path.suffix == '.pyc':
            if '__pycache__' not in path.parts or path.suffix != '.pyc':
                raise ValueError('Unexpected cache artifact in executing freeze')
            caches[name] = expected
        else:
            sources[name] = expected
    if len(sources) != 47:
        raise ValueError('Exactly 47 mandatory source/schema files are required')
    return sources, caches


def portable_source_binding(output, freeze):
    """Preserve generated cache bytes as inert evidence, never restore/execute."""
    sources, caches = frozen_source_sets(freeze.get('code_sha256', {}))
    for name, expected in sources.items():
        if sha(output / 'executed-source' / safe_relative(name)) != expected:
            raise ValueError('Mandatory executing source/schema snapshot changed')
    evidence_path = output / 'generated-bytecode-evidence.json'
    if evidence_path.exists():
        evidence = read(evidence_path)
    else:
        encoded = {}
        for name, expected in caches.items():
            path = output / 'executed-source' / safe_relative(name)
            raw = path.read_bytes()
            if hashlib.sha256(raw).hexdigest() != expected:
                raise ValueError('Generated cache differs before preservation')
            encoded[name] = {'sha256': expected, 'bytes': len(raw),
                             'base64': base64.b64encode(raw).decode('ascii')}
        evidence = {'evidence_only_never_execute': True,
                    'original_freeze_sha256': sha(output / 'freeze.json'), 'entries': encoded}
        atomic_json(evidence_path, evidence)
    if (evidence.get('evidence_only_never_execute') is not True or
            evidence.get('original_freeze_sha256') != sha(output / 'freeze.json') or
            set(evidence.get('entries', {})) != set(caches)):
        raise ValueError('Generated bytecode evidence does not bind the original freeze')
    for name, expected in caches.items():
        value = evidence['entries'][name]
        raw = base64.b64decode(value['base64'], validate=True)
        if (len(raw) != value['bytes'] or value['sha256'] != expected or
                hashlib.sha256(raw).hexdigest() != expected):
            raise ValueError('Generated bytecode lossless evidence hash differs')
        existing = output / 'executed-source' / safe_relative(name)
        if existing.exists() and sha(existing) != expected:
            raise ValueError('Existing compiled cache changed from frozen evidence')
    binding = {'original_freeze_sha256': sha(output / 'freeze.json'),
        'mandatory_source_schema_files': sources, 'mandatory_source_schema_count': len(sources),
        'ancillary_generated_cache_count': len(caches),
        'generated_bytecode_evidence_sha256': sha(evidence_path),
        'all_original_freeze_entries_verified': len(sources) + len(caches),
        'generated_cache_never_executed_or_restored_by_evaluator': True,
        'disclosure': f'The original runner imported the copied snapshot before building its hash map; {len(caches)} generated cache entries are ancillary, 47 source/schema files are mandatory. Original freeze and executing runner are unchanged.'}
    target = output / 'portable-source-binding.json'
    if target.exists():
        if read(target) != binding:
            raise ValueError('Preserve existing portable source binding')
    else:
        atomic_json(target, binding)
    return binding


def prepare(output):
    """No reference or packaging label access is allowed inside preflight."""
    marker, freeze = read(output / 'predictions-complete.json'), read(output / 'freeze.json')
    validate_completion(marker, freeze, sha(output / 'freeze.json'))
    if sha(output / 'executed-runner.py') != freeze.get('runner_sha256'):
        raise ValueError('Executed control runner changed')
    portable_source_binding(output, freeze)
    for name, expected in freeze.get('input_sha256', {}).items():
        if sha(ROOT / safe_relative(name)) != expected:
            raise ValueError('Frozen image, observed producer or public DB input changed')
    if freeze.get('database_sha256') != DB_SHA256:
        raise ValueError('Unexpected public DB snapshot')
    tool_paths = {'syft': ROOT / '.tools/syft/syft.exe',
                  'trivy': ROOT / 'benchmarks/.work/trivy-r34/trivy.exe',
                  'crane': ROOT / 'benchmarks/.work/crane-r94/crane.exe'}
    if set(freeze.get('tool_sha256', {})) != set(tool_paths) or any(
            sha(path) != freeze['tool_sha256'][name] for name, path in tool_paths.items()):
        raise ValueError('Pinned pipeline tools changed')
    predictions = {}
    for name, pair in CASES.items():
        folder = output / name
        invocation, run = read(folder / 'invocation.json'), read(folder / 'run.json')
        if sha(folder / 'run.json') != marker.get('run_sha256', {}).get(name):
            raise ValueError('Terminal run changed after prediction marker')
        archive_name = f'benchmarks/.work/{pair}/image.tar'
        if (invocation.get('oracle_read') is not False or run.get('oracle_read') is not False
                or invocation.get('repository_url') is not None or invocation.get('commit') is not None
                or invocation.get('source_input') is not False
                or invocation.get('java_archive_components_default') is not True
                or invocation.get('java_archive_components_override_supplied') is not False
                or invocation.get('archive') != archive_name
                or invocation.get('archive_sha256') != freeze['input_sha256'].get(archive_name)):
            raise ValueError('Control invocation differs from image-only default freeze')
        analysis = folder / 'analysis'
        if run.get('status') == 'FAILED':
            if analysis.exists() or run.get('final_published') is not False:
                raise ValueError('Failed analysis with published files requires separate validation')
            predictions[name] = {'analysis': None, 'run': run, 'hashes': {}}
            continue
        if run.get('status') != 'completed' or name not in marker.get('completed', []):
            raise ValueError('An unfinished control cannot be evaluated')
        for filename, expected in run.get('output_sha256', {}).items():
            if Path(filename).name != filename or sha(analysis / filename) != expected:
                raise ValueError('Published output seal differs')
        hashes = {}
        for view in ('final', 'os', 'full'):
            filename = view + '.cdx.json'
            validate_cyclonedx(read(analysis / filename))
            hashes[view] = sha(analysis / filename)
            if hashes[view] != run.get('output_sha256', {}).get(filename):
                raise ValueError('Every final/os/full publication must be sealed')
        provenance, source = read(analysis / 'provenance.json'), read(analysis / 'source.syft.json')
        if (source['artifacts'] or provenance.get('source_kind') != 'not-provided'
                or read(analysis / 'summary.json').get('status') != 'succeeded'):
            raise ValueError('Source enrichment or incomplete publication is not image-only')
        predictions[name] = {'analysis': analysis, 'run': run, 'hashes': hashes,
                             'provenance': provenance}
    return freeze, predictions


def bound_reference(name, prediction):
    """First oracle reads: called only after prepare() returns both cases."""
    pair = ROOT / 'benchmarks/references' / CASES[name]
    receipt = read(pair / 'receipt.json')
    for relative, expected in receipt['reference_hashes'].items():
        path = pair / safe_relative(relative)
        if not path.resolve().is_relative_to(pair.resolve()) or sha(path) != expected:
            raise ValueError('Immutable controlled reference changed')
    if receipt.get('artifact_tree_equal') is not True:
        raise ValueError('Controlled build/final tree attestation is absent')
    work = ROOT / 'benchmarks/.work' / CASES[name]
    binding = archive_binding(work / 'image.tar', receipt['image_binding']['index_digest'])
    if binding != receipt['image_binding']:
        raise ValueError('Actual image differs from immutable reference OCI chain')
    tree = read(pair / 'application-tree.json')
    for filename in ('build-app.tar', 'runtime-app.tar'):
        actual, _ = exported_tree(work / filename)
        if actual != tree:
            raise ValueError('Actual controlled application tree changed')
    if prediction['analysis']:
        observed = prediction['provenance']['image']['image_config_digest']
        if observed != binding['config_digest']:
            raise ValueError('Published SBOM image config differs from reference')
        raw = read(prediction['analysis'] / 'image-original.syft.json')
        encoded = raw.get('source', {}).get('metadata', {}).get('config', '')
        if 'sha256:' + hashlib.sha256(base64.b64decode(encoded, validate=True)).hexdigest() != observed:
            raise ValueError('Original producer config is not bound to publication')
    return pair, work, receipt, tree


def component_metrics(actual, expected):
    from score_project_components import metrics
    return {'components': metrics(actual, expected), 'versions': versions(actual, expected),
            'count_delta': len(actual) - len(expected),
            'missing': sorted(expected - actual), 'extra': sorted(actual - expected)}


def own_primary(pair, work, tree, bom, native):
    """Controlled flat recipe ownership proof, separate from dependency scope."""
    effective_raw = (pair / 'effective-pom.xml').read_bytes()
    if len(effective_raw) > 16 * 1024**2 or b'<!DOCTYPE' in effective_raw.upper():
        raise ValueError('Unsupported effective model')
    model = ET.fromstring(effective_raw)
    gav = tuple(one(model, f'm:{key}') for key in ('groupId', 'artifactId', 'version'))
    if any(not SIMPLE.fullmatch(value or '') for value in gav):
        raise ValueError('Primary effective GAV is not literal')
    owner = 'pkg:maven/' + gav[0] + '/' + gav[1] + '@' + gav[2]
    if (coord(bom['metadata']['component']) != owner or
            tuple(native.get(key) for key in ('groupId', 'artifactId', 'version')) != gav):
        raise ValueError('Primary effective/native/CDX owner conflict')
    final_name = one(model, 'm:build/m:finalName')
    if not SIMPLE.fullmatch(final_name or '') or one(model, 'm:build/m:directory') != '/src/target':
        raise ValueError('Unsupported effective primary output path')
    filename = final_name + '.jar'
    candidates = [row for row in tree if row['type'] == '0' and row['path'] == filename]
    if len(candidates) != 1 or filename in dependency_names(native, bom):
        raise ValueError('Primary filename missing or dependency copy may overwrite it')
    digest = candidates[0]['sha256']
    if any(component_hash(c) == digest for c in all_components(bom)):
        raise ValueError('Primary physical hash collides with a controlled dependency')
    dockerfile = (pair / 'Dockerfile').read_text(encoding='utf-8')
    copy = f'cp ./target/{filename} /application/ && '
    if dockerfile.count(copy) != 1 or 'FROM scratch AS runtime\nCOPY --from=build /application /application\n' not in dockerfile:
        raise ValueError('Controlled literal primary copy is not established')
    with (work / 'runtime-app.tar').open('rb') as stream:
        archive, entries, _ = index(stream, (work / 'runtime-app.tar').stat().st_size)
        with archive:
            member = entries.get('/application/' + filename)
            if member is None or not member.isfile() or member.size > 128 * 1024**2:
                raise ValueError('Actual primary regular bytes missing')
            with archive.extractfile(member) as source:
                if hashlib.file_digest(source, 'sha256').hexdigest() != digest:
                    raise ValueError('Actual primary complete SHA256 differs')
            with archive.extractfile(member) as source:
                zip_index(source)
                with zipfile.ZipFile(source) as jar:
                    items = jar.infolist()
                    if len({m.filename for m in items}) != len(items) or any(not safe_member(m) for m in items):
                        raise ValueError('Primary metadata archive is ambiguous or unsafe')
                    properties = [m for m in items if m.filename.endswith('pom.properties')]
                    if len(properties) != 1 or properties[0].file_size > 32 * 1024:
                        raise ValueError('Primary embedded identity is not unique/bounded')
                    if metadata_gav(jar.read(properties[0]), properties[0].filename) != gav:
                        raise ValueError('Primary embedded canonical GAV conflicts')
    return {'owner': owner, 'image_path': '/application/' + filename, 'sha256': digest,
            'method': 'controlled-flat-recipe/effective/native/CDX/canonical-properties/full-physical-SHA256',
            'no_directness_execution_or_publisher_authenticity_claim': True}


def evaluate_case(name, prediction):
    from score_project_components import metrics
    pair, work, receipt, tree = bound_reference(name, prediction)
    bom = read(pair / 'sbom.json')
    owner = coord(bom['metadata']['component'])
    final = read(prediction['analysis'] / 'final.cdx.json') if prediction['analysis'] else None
    if name == 'rest':
        label_path = ROOT / 'benchmarks/results/petclinic-rest-packaging-labels-v1/report.json'
        labels = read(label_path)
        if labels['commit'] != receipt['commit'] or labels['unlabelled_build_reference']:
            raise ValueError('REST packaging labels are unbound or incomplete')
        expected = set(labels['packaged'])
        unknown = labels['unknown_packaged']
        direct = set(labels['root_direct_build'])
        label_info = {'packaging_labels_sha256': sha(label_path), 'primary_owner_exclusion': owner,
                      'known_packaged_labels': len(expected), 'packaging_unknown': unknown,
                      'label_method': 'existing controlled resolved/nested physical SHA256 labels'}
    else:
        native = read(pair / 'dependency-tree.json')
        primary = own_primary(pair, work, tree, bom, native)
        by_hash = defaultdict(set)
        for component in all_components(bom):
            if coord(component) and component_hash(component):
                by_hash[component_hash(component)].add(coord(component))
        expected, unknown, known = set(), [], []
        for row in tree:
            if row['type'] != '0' or not row['path'].lower().endswith('.jar'):
                continue
            if '/application/' + row['path'] == primary['image_path'] and row['sha256'] == primary['sha256']:
                continue
            choices = by_hash.get(row['sha256'], set())
            if len(choices) == 1:
                coordinate = next(iter(choices))
                expected.add(coordinate)
                known.append({'image_path': '/application/' + row['path'], 'sha256': row['sha256'],
                              'coordinate': coordinate})
            else:
                unknown.append({'image_path': '/application/' + row['path'], 'sha256': row['sha256'],
                                'status': 'UNKNOWN', 'reason': 'No unique controlled CDX SHA256 identity'})
        direct = {'pkg:maven/' + '/'.join(gav[:2]) + '@' + gav[2]
                  for gav in read(pair / 'direct-labels.json')['direct']}
        label_info = {'primary_owner_exclusion': primary, 'known_standalone_labels': known,
                      'packaging_unknown': unknown,
                      'label_method': 'actual controlled build/runtime TAR SHA256 joined to own CDX hash'}
    if not expected:
        raise ValueError('Empty component controls are not acceptance successes')
    actual = projected(final, '/application/', owner) if final else set()
    result = {**component_metrics(actual, expected), **label_info,
        'project': receipt['project'], 'commit': receipt['commit'],
        'image_config_binding_verified': True, 'actual_build_runtime_application_trees_verified': True,
        'scope': 'known controlled SHA256-labelled delivered project dependencies under /application/',
        'full_shaded_component_scope_attested': False,
        'known_unknown_is_not_absence': True,
        'packaging_unknown_charged_conservative_fp_if_predicted': len(unknown),
        'raw_build_component_count': len({coord(c) for c in all_components(bom) if coord(c)} - {owner}),
        'raw_build_reference_delta': component_metrics(actual,
            {coord(c) for c in all_components(bom) if coord(c)} - {owner}),
        'direct': metrics(set(), direct), 'direct_status': 'UNKNOWN_NO_SOURCE_INPUT',
        'status': prediction['run']['status'], 'seconds': prediction['run']['elapsed_seconds'],
        'output_sha256': prediction['hashes']}
    if prediction['analysis']:
        result['summary'] = read(prediction['analysis'] / 'summary.json')
        result['java_image_status'] = prediction['provenance']['image'].get('java_image_status')
        result['reader_policy'] = prediction['provenance']['image'].get('java_reader_policy')
        result['raw_syft_project_coordinates'] = sorted({coord(c) for c in
            read(prediction['analysis'] / 'image-original.syft.json')['artifacts'] if coord(c) and any(
                row.get('path', '').startswith('/application/') for row in c.get('locations', []))} - {owner})
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    output = parser.parse_args().output.resolve()
    if (output / 'evaluation.json').exists():
        raise FileExistsError('Preserve completed held-control evaluation')
    freeze, predictions = prepare(output)
    # First reference/packaging-label access occurs only after both preflights.
    results = {name: evaluate_case(name, predictions[name]) for name in CASES}
    rows = [result['components'] for result in results.values()]
    passed = all(result['status'] == 'completed' and result['components']['reference'] > 0
                 and all(result['components'][key] is not None and result['components'][key] > .9
                         for key in ('precision', 'recall'))
                 and result['versions']['exact_version_coverage'] > .9 for result in results.values())
    report = {'mode': freeze['execution_mode'], 'partition': freeze['partition'],
        'fresh_blind_independent_claim': False, 'source_input': False,
        'fresh_scanners': True, 'fresh_physical_reads': True, 'release_default_evaluated': True,
        'reports': results, 'java_components_micro': aggregate(rows),
        'java_components_macro_across_projects': macro(rows),
        'java_direct': aggregate([result['direct'] for result in results.values()]),
        'two_held_known_delivered_component_controls_over_90': passed,
        'universal_accuracy_or_complete_unknown_ci_graph_claim': False, 'acceptance': False,
        'limitations': ['Existing historically disclosed controls; held from recent Java tuning, not fresh blind projects',
                       'Known delivered SHA256 artifact scope does not prove absence or identity of shaded components',
                       'Packaging UNKNOWN remains explicit and predicted extras conservatively FP',
                       'Image-only direct graph is UNKNOWN; no original TeamCity graph claim',
                       'Registry acquisition is excluded by local immutable archives; hard quota/concurrency/cold DB acceptance separate'],
        'freeze_sha256': sha(output / 'freeze.json')}
    report['portable_source_binding_sha256'] = sha(output / 'portable-source-binding.json')
    atomic_json(output / 'evaluation.json', report)
    print(json.dumps({name: result['components'] for name, result in results.items()}))


if __name__ == '__main__':
    main()
